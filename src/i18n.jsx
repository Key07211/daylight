export function translate(lang, zh, en) {
  return lang === "en" ? (en ?? english[zh] ?? zh) : zh;
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLanguage] = useState(() => {
    try { return localStorage.getItem("daylight-language") === "en" ? "en" : "zh"; }
    catch { return "zh"; }
  });
  const setLang = (next) => setLanguage(next === "en" ? "en" : "zh");
  useLayoutEffect(() => {
    document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
    try { localStorage.setItem("daylight-language", lang); } catch { /* Keep the switch usable without storage. */ }
  }, [lang]);
  const value = useMemo(() => ({
    lang, setLang, locale: lang === "en" ? "en-US" : "zh-CN",
    t: (zh, en) => translate(lang, zh, en),
  }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n requires I18nProvider");
  return context;
}

export function LanguageSwitch({ rainIntensity = 0, animated = true }) {
  const { lang, setLang, t } = useI18n();
  return (
    <section className="language-card" aria-label={t("界面语言")}>
      <GlassRain intensity={rainIntensity} animated={animated} />
      <div className="language-card-heading"><Languages size={17} /><h3>{t("界面语言")}</h3></div>
      <div className="language-options" role="group" aria-label={t("界面语言")}>
        <button type="button" data-language="zh" lang="zh-CN" aria-pressed={lang === "zh"} onClick={() => setLang("zh")}>中文</button>
        <button type="button" data-language="en" lang="en" aria-pressed={lang === "en"} onClick={() => setLang("en")}>English</button>
      </div>
    </section>
  );
}
